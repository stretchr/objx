// Command codegen generates the type-specific accessors in
// type_specific_codegen.go and their tests in type_specific_codegen_test.go.
//
// Run it from the repository root with:
//
//	go generate ./...
package main

import (
	"bytes"
	"embed"
	"fmt"
	"go/format"
	"log"
	"os"
	"text/template"
)

const header = "// Code generated by \"go run ./codegen\"; DO NOT EDIT.\n\n"

// typ describes one type to generate accessors for.
type typ struct {
	// Name is the method name stem, e.g. "Str" gives Str, MustStr, StrSlice, ...
	Name string
	// Type is the Go type.
	Type string
	// Example is a non-zero literal of Type, used in tests.
	Example string
	// Zero is the zero value of Type.
	Zero string
	// FromFloat64 makes the getters also accept a float64 holding a whole
	// number, which is how encoding/json decodes numbers.
	FromFloat64 bool
}

// types lists the generated types in output order. Map and Map slices are
// handled by hand in type_specific.go.
var types = []typ{
	{Name: "Inter", Type: "any", Example: `"something"`, Zero: "nil"},
	{Name: "Bool", Type: "bool", Example: "true", Zero: "false"},
	{Name: "Str", Type: "string", Example: `"hello"`, Zero: `""`},
	{Name: "Int", Type: "int", Example: "1", Zero: "0", FromFloat64: true},
	{Name: "Int8", Type: "int8", Example: "1", Zero: "0"},
	{Name: "Int16", Type: "int16", Example: "1", Zero: "0"},
	{Name: "Int32", Type: "int32", Example: "1", Zero: "0"},
	{Name: "Int64", Type: "int64", Example: "1", Zero: "0"},
	{Name: "Uint", Type: "uint", Example: "1", Zero: "0"},
	{Name: "Uint8", Type: "uint8", Example: "1", Zero: "0"},
	{Name: "Uint16", Type: "uint16", Example: "1", Zero: "0"},
	{Name: "Uint32", Type: "uint32", Example: "1", Zero: "0"},
	{Name: "Uint64", Type: "uint64", Example: "1", Zero: "0"},
	{Name: "Uintptr", Type: "uintptr", Example: "1", Zero: "0"},
	{Name: "Float32", Type: "float32", Example: "1", Zero: "0"},
	{Name: "Float64", Type: "float64", Example: "1", Zero: "0"},
	{Name: "Complex64", Type: "complex64", Example: "1", Zero: "0"},
	{Name: "Complex128", Type: "complex128", Example: "1", Zero: "0"},
}

//go:embed *.go.tmpl
var templates embed.FS

func main() {
	for tmpl, out := range map[string]string{
		"type_specific.go.tmpl":      "type_specific_codegen.go",
		"type_specific_test.go.tmpl": "type_specific_codegen_test.go",
	} {
		if err := generate(tmpl, out); err != nil {
			log.Fatal(err)
		}
	}
}

func generate(tmpl, out string) error {
	t, err := template.ParseFS(templates, tmpl)
	if err != nil {
		return err
	}

	buf := bytes.NewBufferString(header)
	if err := t.Execute(buf, types); err != nil {
		return err
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("formatting %s: %w", out, err)
	}
	return os.WriteFile(out, src, 0o644)
}
